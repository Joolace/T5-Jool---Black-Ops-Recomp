import argparse
import csv
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[2] / "src" / "stringed"
ENCODINGS = {
    "en": "cp1252", "fr": "cp1252", "de": "cp1252", "it": "cp1252",
    "es": "cp1252", "ru": "cp1251", "pl": "cp1250", "ko": "cp949",
    "ja": "cp932", "cs": "cp1250",
}
FORMAT = re.compile(r"%(?:%|(?:\.\d+)?[dfs])")


def literal(value):
    return '"' + "".join(
        chr(byte) if 32 <= byte <= 126 and byte not in (34, 92) else f"\\{byte:03o}"
        for byte in value
    ) + '"'


def generate():
    rows = {}
    with (ROOT / "port_ui_translations.tsv").open(encoding="utf-8", newline="") as source:
        reader = csv.DictReader(source, delimiter="\t")
        if reader.fieldnames != ["key", *ENCODINGS]:
            raise ValueError("Unexpected language columns")
        for row in reader:
            key = row.pop("key")
            if key in rows or not re.fullmatch(r"[A-Z_]+", key):
                raise ValueError(f"Invalid or repeated key: {key}")
            formats = FORMAT.findall(row["en"])
            values = []
            for language, encoding in ENCODINGS.items():
                value = row[language]
                if not value or FORMAT.findall(value) != formats or "%" in FORMAT.sub("", value):
                    raise ValueError(f"{key}: missing text or mismatched format in {language}")
                values.append((literal(value.encode(encoding)), literal(value.encode("utf-8"))))
            rows[key] = values

    lines = ["// Generated by tools/nx/generate-port-ui-translations.py."]
    for key, values in sorted(rows.items()):
        lines.append(f'    {{"OPENBLOPS_{key}",')
        for index in (0, 1):
            lines.append("        {")
            lines.extend(f"            {value[index]}," for value in values)
            lines.append("        }," if index == 0 else "        }},")
    return "\n".join(lines) + "\n"


parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
output = ROOT / "port_ui_translations.inc"
generated = generate()
if args.check:
    if output.read_text(encoding="ascii") != generated:
        parser.exit(1, "port_ui_translations.inc is out of date\n")
else:
    output.write_text(generated, encoding="ascii", newline="\n")
